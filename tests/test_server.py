    assert "MyApp" in result
    assert (tmp_path / "deployed" / "main.py").exists()
    assert (tmp_path / "deployed" / "config" / "settings.py").exists()
    assert (tmp_path / "deployed" / "models" / "user.py").exists()
    assert (tmp_path / "deployed" / "repositories" / "user_repo.py").exists()
    assert (tmp_path / "deployed" / "migrations" / "manager.py").exists()
    assert (tmp_path / "deployed" / "wsqlite.config.json").exists()


