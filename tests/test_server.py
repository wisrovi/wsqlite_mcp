def test_search_wsqlite_pattern_returns_results():
    patterns = [
        {
            "origin": "Official",
            "name": "model_crud_basic",
            "feature": "WSQLite CRUD",
            "module": "wsqlite",
            "description": "auto table creation",
        },
        {
            "origin": "Community",
            "name": "fts5_search",
            "feature": "FTS5",
            "module": "wsqlite",
            "description": "full-text search",
        },
    ]
    catalog_mock = mock.MagicMock()
    catalog_mock.search.return_value = patterns
    with mock.patch.object(server, "get_catalog", return_value=catalog_mock):
        text = server.search_wsqlite_pattern("crud")
    assert "model_crud_basic" in text
    assert "WSQLite CRUD" in text
    assert "wsqlite" in text
    assert "auto table creation" in text
    assert "Official" in text
    assert "Community" in text


def test_search_wsqlite_pattern_no_results():
    catalog_mock = mock.MagicMock()
    catalog_mock.search.return_value = []
    with mock.patch.object(server, "get_catalog", return_value=catalog_mock):
        text = server.search_wsqlite_pattern("zzz_nope")
    assert "No pattern matching 'zzz_nope' was found" in text
    assert "native WSQLite pattern" in text


